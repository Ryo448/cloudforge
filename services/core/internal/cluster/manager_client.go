type LinkResult struct {
	Status           string `json:"status"`
	VerificationCode string `json:"verificationCode"`
	PrimaryID        string `json:"primaryId"`
	PrimaryName      string `json:"primaryName"`
	PrimaryURL       string `json:"primaryUrl"`
	DisplayName      string `json:"displayName"`
	ExpiresAt        int64  `json:"expiresAt"`
}

// StartLink initiates pairing on secondary X using an invite generated by Y.
// Always generates a fresh keypair stored in the OS secure vault so a previously
// revoked key can never be reused.
func (m *Manager) StartLink(ctx context.Context, inviteToken, displayName string) (LinkResult, error) {
	invite, err := DecodeInvite(inviteToken, m.Development)
	if err != nil {
		return LinkResult{}, err
	}
	if invite.PrimaryID == m.InstallationID {
		return LinkResult{}, errors.New("não é possível vincular um computador a si mesmo")
	}
	if time.Now().Unix() > invite.ExpiresAt {
		return LinkResult{}, errors.New("convite expirado; gere um novo convite no computador principal")
	}

	st, err := m.loadState()
	if err != nil {
		return LinkResult{}, err
	}
	if st.Role == RolePrimary {
		nodes, _ := m.listNodes("")
		if len(nodes) > 0 {
			return LinkResult{}, errors.New("remova todos os computadores vinculados antes de vincular esta instalação a outro painel principal")
		}
	}
	if st.Role == RoleSecondary && st.LinkStatus == LinkStatusLinked {
		return LinkResult{}, errors.New("este computador já está vinculado a um painel principal")
	}

	if strings.TrimSpace(displayName) == "" {
		displayName = st.DisplayName
		if displayName == "" {
			displayName = defaultDisplayName()
		}
	}
	displayName, err = sanitizeDisplayName(displayName)
	if err != nil {
		return LinkResult{}, err
	}

	// Stop any previous pending link attempt before generating a fresh identity key.
	m.stopSecondaryLoop()

	id, err := m.ensureIdentity(true)
	if err != nil {
		return LinkResult{}, err
	}

	// Dial Y synchronously to submit pair_request and obtain immediate validation + verification code.
	tlsConn, primaryPub, err := m.dialPrimaryMTLS(ctx, invite.PrimaryURL, invite.PrimaryFingerprint, id)
	if err != nil {
		return LinkResult{}, fmt.Errorf("não foi possível conectar ao computador principal: %w", err)
	}
	peer := newPeerConn(invite.PrimaryID, invite.PrimaryFingerprint, primaryPub, tlsConn, false)

	host, goOS, goArch := m.hostnameOSArch()
	helloID := auth.ID()
	if err := peer.send(MsgHello, helloID, "", HelloMsg{
		NodeID:      m.InstallationID,
		Mode:        "pair",
		DisplayName: displayName,
		Hostname:    host,
		OS:          goOS,
		Arch:        goArch,
		AppVersion:  m.AppVersion,
	}); err != nil {
		peer.close()
		return LinkResult{}, err
	}
	_ = tlsConn.SetReadDeadline(time.Now().Add(15 * time.Second))
	ackEnv, err := readFrame(tlsConn)
	if err != nil || ackEnv.Type != MsgHelloAck {
		peer.close()
		return LinkResult{}, errors.New("falha ao iniciar protocolo com o painel principal")
	}
	var ack HelloAckMsg
	if json.Unmarshal(ackEnv.Payload, &ack) != nil || !ack.OK {
		peer.close()
		if ack.Error != "" {
			return LinkResult{}, errors.New(ack.Error)
		}
		return LinkResult{}, errors.New("o painel principal rejeitou a conexão de pareamento")
	}

	reqID := auth.ID()
	if err := peer.send(MsgPairRequest, reqID, "", PairRequestMsg{
		InviteID:     invite.InviteID,
		Secret:       invite.Secret,
		NodeID:       m.InstallationID,
		DisplayName:  displayName,
		Hostname:     host,
		OS:           goOS,
		Arch:         goArch,
		PublicKeyPEM: id.PublicKeyPEM,
		DelegatedOps: st.DelegatedOps,
	}); err != nil {
		peer.close()
		return LinkResult{}, err
	}
	_ = tlsConn.SetReadDeadline(time.Now().Add(15 * time.Second))
	respEnv, err := readFrame(tlsConn)
	if err != nil || respEnv.Type != MsgPairResponse {
		peer.close()
		return LinkResult{}, errors.New("resposta inválida durante o pareamento")
	}
	var resp PairResponseMsg
	if json.Unmarshal(respEnv.Payload, &resp) != nil {
		peer.close()
		return LinkResult{}, errors.New("resposta inválida durante o pareamento")
	}
	if !resp.Accepted {
		peer.close()
		if resp.Error != "" {
			return LinkResult{}, errors.New(resp.Error)
		}
		return LinkResult{}, errors.New("convite rejeitado pelo computador principal")
	}

	// Independently verify the Short Authentication String matches our own computation!
	expectedCode := VerificationCode(invite.PrimaryID, invite.PrimaryFingerprint, m.InstallationID, id.Fingerprint, invite.InviteID)
	if resp.VerificationCode != expectedCode {
		peer.close()
		return LinkResult{}, errors.New("código de conferência divergente; pareamento abortado por segurança")
	}

	primaryName := resp.PrimaryName
	if primaryName == "" {
		primaryName = invite.PrimaryName
	}
	primaryURL := invite.PrimaryURL
	if resp.PrimaryURL != "" {
		primaryURL = resp.PrimaryURL
	}

	// Persist pending link state (NEVER persist invite.Secret to SQLite!).
	st, err = m.loadState()
	if err != nil {
		peer.close()
		return LinkResult{}, err
	}
	st.DisplayName = displayName
	st.PrimaryURL = primaryURL
	st.PrimaryID = invite.PrimaryID
	st.PrimaryName = primaryName
	st.PrimaryFingerprint = invite.PrimaryFingerprint
	st.PendingInviteID = invite.InviteID
	st.VerificationCode = expectedCode
	st.LinkStatus = LinkStatusPendingApproval
	if err := m.saveState(st); err != nil {
		peer.close()
		return LinkResult{}, err
	}

	// Hand the live pending mTLS connection to the background watcher so approval transitions seamlessly!
	m.startPendingWatcher(peer, primaryPub, invite.ExpiresAt)

	return LinkResult{
		Status:           LinkStatusPendingApproval,
		VerificationCode: expectedCode,
		PrimaryID:        invite.PrimaryID,
		PrimaryName:      primaryName,
		PrimaryURL:       primaryURL,
		DisplayName:      displayName,
		ExpiresAt:        invite.ExpiresAt,
	}, nil
}

// CancelLink cancels a pending pairing request or clears a revoked/rejected status
// without republishing the local panel automatically.
func (m *Manager) CancelLink() error {
	m.stopSecondaryLoop()
	st, err := m.loadState()
	if err != nil {
		return err
	}
	if st.Role == RoleSecondary && st.LinkStatus == LinkStatusLinked {
		return errors.New("para desvincular um computador ativo, remova-o no painel principal")
	}
	st.Role = RoleStandalone
	st.LinkStatus = LinkStatusNone
	st.PrimaryURL = ""
	st.PrimaryID = ""
	st.PrimaryName = ""
	st.PrimaryFingerprint = ""
	st.PendingInviteID = ""
	st.VerificationCode = ""
	st.AccessSlug = ""
	return m.saveState(st)
}

func (m *Manager) dialPrimaryMTLS(ctx context.Context, primaryURL, primaryFP string, id *Identity) (*tls.Conn, *ecdsa.PublicKey, error) {
	wsURL := strings.TrimRight(primaryURL, "/") + "/api/cluster/ws"
	if strings.HasPrefix(wsURL, "https://") {
		wsURL = "wss://" + strings.TrimPrefix(wsURL, "https://")
	} else if strings.HasPrefix(wsURL, "http://") {
		wsURL = "ws://" + strings.TrimPrefix(wsURL, "http://")
	} else {
		return nil, nil, errors.New("URL do painel principal inválida")
	}

	dialer := m.Dialer
	if dialer == nil {
		dialer = &websocket.Dialer{
			HandshakeTimeout: 15 * time.Second,
			Proxy:            http.ProxyFromEnvironment,
		}
	}
	dialCtx, cancel := context.WithTimeout(ctx, 15*time.Second)
	defer cancel()
	ws, _, err := dialer.DialContext(dialCtx, wsURL, http.Header{})
	if err != nil {
		return nil, nil, err
	}
	rawConn := newWSNetConn(ws)
	tlsConn := tls.Client(rawConn, clientTLSConfig(id, primaryFP))
	_ = tlsConn.SetDeadline(time.Now().Add(15 * time.Second))
	if err := tlsConn.HandshakeContext(dialCtx); err != nil {
		_ = tlsConn.Close()
		return nil, nil, err
	}
	state := tlsConn.ConnectionState()
	if len(state.PeerCertificates) == 0 {
		_ = tlsConn.Close()
		return nil, nil, errors.New("certificado do principal ausente")
	}
	_, primaryPub, _, err := verifyPeerSelfSignedCert(state.PeerCertificates[0].Raw)
	if err != nil {
		_ = tlsConn.Close()
		return nil, nil, err
	}
	return tlsConn, primaryPub, nil
}

func (m *Manager) stopSecondaryLoop() {
	m.clientMu.Lock()
	cancel := m.clientCancel
	done := m.clientDone
	conn := m.clientConn
	m.clientCancel = nil
	m.clientDone = nil
	m.clientConn = nil
	m.clientConnected = false
	m.clientMu.Unlock()
	if conn != nil {
		conn.close()
	}
	if cancel != nil {
		cancel()
	}
	if done != nil {
		<-done
	}
}

func (m *Manager) startPendingWatcher(peer *peerConn, primaryPub *ecdsa.PublicKey, expiresAt int64) {
	m.clientMu.Lock()
	if m.clientCancel != nil {
		m.clientCancel()
	}
	m.mu.RLock()
	parent := m.rootCtx
	m.mu.RUnlock()
	ctx, cancel := context.WithCancel(parent)
	done := make(chan struct{})
	m.clientCancel = cancel
	m.clientDone = done
	m.clientConn = peer
	m.clientPrimaryPub = primaryPub
	m.clientLastErr = ""
	m.clientMu.Unlock()

	go func() {
		defer close(done)
		defer peer.close()

		// Send periodic heartbeats while waiting for admin approval on Y.
		hbDone := make(chan struct{})
		go func() {
			defer close(hbDone)
			ticker := time.NewTicker(m.HeartbeatInterval)
			defer ticker.Stop()
			for {
				select {
				case <-ctx.Done():
					return
				case <-peer.closed:
					return
				case <-ticker.C:
					_ = peer.send(MsgHeartbeat, auth.ID(), "", HeartbeatMsg{SentAt: time.Now().Unix()})
				}
			}
		}()

		approved := false
		for {
			select {
			case <-ctx.Done():
				return
			default:
			}
			_ = peer.conn.SetReadDeadline(time.Now().Add(m.HeartbeatTimeout))
			env, err := readFrame(peer.conn)
			if err != nil {
				break
			}
			switch env.Type {
			case MsgHeartbeatAck:
				continue
			case MsgPairApproved:
				var msg PairApprovedMsg
				if json.Unmarshal(env.Payload, &msg) == nil {
					st, err := m.loadState()
					if err == nil {
						st.AccessSlug = msg.AccessSlug
						if msg.PrimaryName != "" {
							st.PrimaryName = msg.PrimaryName
						}
						if msg.PrimaryURL != "" {
							st.PrimaryURL = msg.PrimaryURL
						}
						st.VerificationCode = ""
						st.PendingInviteID = ""
						st.LinkStatus = LinkStatusSyncing
						_ = m.saveState(st)
					}
					approved = true
				}
			case MsgPairRejected:
				st, err := m.loadState()
				if err == nil {
					st.LinkStatus = LinkStatusRejected
					st.VerificationCode = ""
					st.PendingInviteID = ""
					_ = m.saveState(st)
				}
				return
			case MsgNodeRevoked:
				m.handleRevokedLocally()
				return
			}
			if approved {
				break
			}
		}

		peer.close()
		<-hbDone

		if ctx.Err() != nil {
			return
		}
		if approved {
			// Transition directly into the persistent secondary session loop!
			m.runSecondarySessionLoop(ctx)
			return
		}
		// If connection dropped while pending before expiry, keep trying session mode in case Y already approved!
		if time.Now().Unix() < expiresAt {
			m.runSecondarySessionLoop(ctx)
		}
	}()
}

func (m *Manager) startSecondaryLoop() {
	m.clientMu.Lock()
	if m.clientCancel != nil {
		m.clientMu.Unlock()
		return
	}
	m.mu.RLock()
	parent := m.rootCtx
	m.mu.RUnlock()
	ctx, cancel := context.WithCancel(parent)
	done := make(chan struct{})
	m.clientCancel = cancel
	m.clientDone = done
	m.clientMu.Unlock()

	go func() {
		defer close(done)
		m.runSecondarySessionLoop(ctx)
	}()
}

func (m *Manager) runSecondarySessionLoop(ctx context.Context) {
	delay := m.ReconnectBaseDelay
	if delay <= 0 {
		delay = time.Second
	}
	maxDelay := m.ReconnectMaxDelay
	if maxDelay < delay {
		maxDelay = 60 * time.Second
	}

	for {
		if ctx.Err() != nil {
			return
		}
		st, err := m.loadState()
		if err != nil || st.PrimaryURL == "" || st.PrimaryFingerprint == "" {
			return
		}
		if st.LinkStatus == LinkStatusRevoked || st.LinkStatus == LinkStatusRejected {
			return
		}
		id, err := m.ensureIdentity(false)
		if err != nil {
			m.setClientStatus(false, err.Error())
		} else {
			stopLoop, connectedOnce, sessionErr := m.runSingleSecondarySession(ctx, st, id)
			if stopLoop {
				return
			}
			if connectedOnce {
				delay = m.ReconnectBaseDelay
			}
			if sessionErr != nil {
				m.setClientStatus(false, sessionErr.Error())
			}
		}

		wait := delay
		if st.LinkStatus == LinkStatusPendingApproval && wait > 5*time.Second {
			wait = 5 * time.Second
		}
		select {
		case <-ctx.Done():
			return
		case <-time.After(wait):
			delay *= 2
			if delay > maxDelay {
				delay = maxDelay
			}
		}
	}
}

func (m *Manager) setClientStatus(connected bool, lastErr string) {
	m.clientMu.Lock()
	m.clientConnected = connected
	m.clientLastErr = lastErr
	m.clientMu.Unlock()
}

func (m *Manager) handleRevokedLocally() {
	st, err := m.loadState()
	if err != nil {
		return
	}
	// Preserve local data, processes, databases, tunnel, and service domains.
	// Do NOT republish the standalone panel automatically (CloudConfig.PanelDisabled remains true).
	st.Role = RoleStandalone
	st.LinkStatus = LinkStatusRevoked
	st.VerificationCode = ""
	st.PendingInviteID = ""
	_ = m.saveState(st)
	m.setClientStatus(false, "vínculo revogado pelo computador principal")
}

func (m *Manager) runSingleSecondarySession(ctx context.Context, st LocalState, id *Identity) (stopLoop bool, connectedOnce bool, err error) {
	tlsConn, primaryPub, err := m.dialPrimaryMTLS(ctx, st.PrimaryURL, st.PrimaryFingerprint, id)
	if err != nil {
		return false, false, err
	}
	peer := newPeerConn(st.PrimaryID, st.PrimaryFingerprint, primaryPub, tlsConn, true)
	defer peer.close()

	host, goOS, goArch := m.hostnameOSArch()
	helloID := auth.ID()
	if err := peer.send(MsgHello, helloID, "", HelloMsg{
		NodeID:      m.InstallationID,
		Mode:        "session",
		DisplayName: st.DisplayName,
		Hostname:    host,
		OS:          goOS,
		Arch:        goArch,
		AppVersion:  m.AppVersion,
	}); err != nil {
		return false, false, err
	}
	_ = tlsConn.SetReadDeadline(time.Now().Add(15 * time.Second))
	ackEnv, err := readFrame(tlsConn)
	if err != nil || ackEnv.Type != MsgHelloAck {
		return false, false, errors.New("falha ao autenticar canal com o painel principal")
	}
	var ack HelloAckMsg
	if json.Unmarshal(ackEnv.Payload, &ack) != nil {
		return false, false, errors.New("resposta inválida do painel principal")
	}
	if !ack.OK {
		if ack.ErrorCode == "revoked" {
			m.handleRevokedLocally()
			return true, false, errors.New(ack.Error)
		}
		return false, false, errors.New(ack.Error)
	}

	// Update primary name / accessSlug if updated on Y.
	if fresh, loadErr := m.loadState(); loadErr == nil {
		changed := false
		if ack.AccessSlug != "" && fresh.AccessSlug != ack.AccessSlug {
			fresh.AccessSlug = ack.AccessSlug
			changed = true
		}
		if ack.PrimaryName != "" && fresh.PrimaryName != ack.PrimaryName {
			fresh.PrimaryName = ack.PrimaryName
			changed = true
		}
		if ack.PrimaryURL != "" && fresh.PrimaryURL != ack.PrimaryURL {
			fresh.PrimaryURL = ack.PrimaryURL
			changed = true
		}
		if changed {
			_ = m.saveState(fresh)
		}
	}

	m.clientMu.Lock()
	m.clientConn = peer
	m.clientPrimaryPub = primaryPub
	m.clientConnected = true
	m.clientLastErr = ""
	m.clientMu.Unlock()
	defer func() {
		m.clientMu.Lock()
		if m.clientConn == peer {
			m.clientConn = nil
		}
		m.clientConnected = false
		m.clientMu.Unlock()
	}()

	// Send initial inventory immediately.
	if err := m.sendInventory(ctx, peer); err != nil {
		return false, true, err
	}

	sessionCtx, cancelSession := context.WithCancel(ctx)
	defer cancelSession()

	bgDone := make(chan struct{})
	go func() {
		defer close(bgDone)
		hbTicker := time.NewTicker(m.HeartbeatInterval)
		invTicker := time.NewTicker(m.InventoryInterval)
		defer hbTicker.Stop()
		defer invTicker.Stop()
		for {
			select {
			case <-sessionCtx.Done():
				return
			case <-peer.closed:
				return
			case <-hbTicker.C:
				var tunnel TunnelHealthReport
				var users []RemoteUserSummary
				if m.Provider != nil {
					tunnel = m.Provider.LocalTunnelHealth(sessionCtx)
					users = m.Provider.LocalAdminUsers()
				}
				if err := peer.send(MsgHeartbeat, auth.ID(), "", HeartbeatMsg{
					SentAt: time.Now().Unix(),
					Tunnel: tunnel,
					Users:  users,
				}); err != nil {
					peer.close()
					return
				}
			case <-invTicker.C:
				_ = m.sendInventory(sessionCtx, peer)
			case <-m.inventoryWake:
				_ = m.sendInventory(sessionCtx, peer)
			}
		}
	}()

	var loopErr error
	for {
		select {
		case <-ctx.Done():
			cancelSession()
			peer.close()
			<-bgDone
			return true, true, nil
		default:
		}
		_ = peer.conn.SetReadDeadline(time.Now().Add(m.HeartbeatTimeout))
		env, err := readFrame(peer.conn)
		if err != nil {
			loopErr = err
			break
		}
		switch env.Type {
		case MsgHeartbeatAck:
			var hbAck HeartbeatAckMsg
			if json.Unmarshal(env.Payload, &hbAck) == nil && hbAck.PrimaryURL != "" {
				if fresh, loadErr := m.loadState(); loadErr == nil && fresh.PrimaryURL != hbAck.PrimaryURL {
					fresh.PrimaryURL = hbAck.PrimaryURL
					_ = m.saveState(fresh)
				}
			}
		case MsgInventoryAck:
			var invAck InventoryAckMsg
			if json.Unmarshal(env.Payload, &invAck) == nil && invAck.Confirmed {
				m.commitSecondaryRoleAfterInventoryAck(sessionCtx, invAck)
			}
		case MsgAuthVerify:
			go m.handleInboundAuthVerify(peer, env)
		case MsgAuthReauth:
			go m.handleInboundAuthReauth(peer, env)
		case MsgAuthStatus:
			go m.handleInboundAuthStatus(peer, env)
		case MsgExecCommand:
			go m.handleInboundExecCommand(sessionCtx, peer, primaryPub, env)
		case MsgNodeRevoked:
			m.handleRevokedLocally()
			cancelSession()
			peer.close()
			<-bgDone
			return true, true, errors.New("vínculo revogado pelo computador principal")
		default:
			loopErr = errors.New("mensagem desconhecida recebida do principal")
			cancelSession()
			peer.close()
			<-bgDone
			return false, true, loopErr
		}
	}

	cancelSession()
	peer.close()
	<-bgDone
	return false, true, loopErr
}

func (m *Manager) sendInventory(ctx context.Context, peer *peerConn) error {
	m.clientMu.Lock()
	m.inventorySeq++
	seq := m.inventorySeq
	m.clientMu.Unlock()

	host, goOS, goArch := m.hostnameOSArch()
	msg := InventorySyncMsg{
		Seq:          seq,
		SyncedAt:     time.Now().Unix(),
		Hostname:     host,
		OS:           goOS,
		Arch:         goArch,
		Projects:     []SanitizedProject{},
		Databases:    []databases.Instance{},
		DelegatedOps: m.State().DelegatedOps,
	}
	if m.Provider != nil {
		msg.Projects = m.Provider.LocalProjects()
		msg.Tunnel = m.Provider.LocalTunnelHealth(ctx)
		msg.Users = m.Provider.LocalAdminUsers()
		if dbView, err := m.Provider.LocalDatabases(ctx); err == nil {
			msg.DockerReady = dbView.Docker
			msg.DockerStatus = string(dbView.DockerStatus)
			for _, db := range dbView.Databases {
				db.LANFirewall = ""
				msg.Databases = append(msg.Databases, db)
			}
		}
	}
	return peer.send(MsgInventorySync, auth.ID(), "", msg)
}

func (m *Manager) commitSecondaryRoleAfterInventoryAck(ctx context.Context, ack InventoryAckMsg) {
	st, err := m.loadState()
	if err != nil {
		return
	}
	needsTransition := st.Role != RoleSecondary || st.LinkStatus != LinkStatusLinked
	if ack.AccessSlug != "" {
		st.AccessSlug = ack.AccessSlug
	}
	if ack.PrimaryURL != "" {
		st.PrimaryURL = ack.PrimaryURL
	}
	if needsTransition {
		st.Role = RoleSecondary
		st.LinkStatus = LinkStatusLinked
		st.VerificationCode = ""
		st.PendingInviteID = ""
		if st.LinkedAt == 0 {
			st.LinkedAt = time.Now().Unix()
		}
		if err := m.saveState(st); err != nil {
			return
		}
		m.RecordAudit(AuditEntry{
			ActorNodeID:  st.PrimaryID,
			TargetNodeID: m.InstallationID,
			ResourceType: "computer",
			ResourceID:   m.InstallationID,
			Operation:    "node.linked_secondary",
			Result:       "success",
			Detail:       "primary=" + st.PrimaryID,
		})
		// Only after Y confirms receipt of initial inventory: unpublish X's local web panel!
		if m.Provider != nil {
			go func() {
				unpubCtx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
				defer cancel()
				_, _ = m.Provider.UnpublishLocalPanel(unpubCtx)
			}()
		}
	} else {
		_ = m.saveState(st)
	}
}

func (m *Manager) handleInboundAuthVerify(peer *peerConn, env Envelope) {
	var req AuthVerifyReq
	if json.Unmarshal(env.Payload, &req) != nil {
		_ = peer.send(MsgAuthVerifyResult, "", env.ID, AuthVerifyResp{OK: false, StatusCode: http.StatusBadRequest, Error: "requisição inválida"})
		return
	}
	if m.Provider == nil {
		_ = peer.send(MsgAuthVerifyResult, "", env.ID, AuthVerifyResp{OK: false, StatusCode: http.StatusServiceUnavailable, Error: "autenticação indisponível"})
		return
	}
	userID, username, epoch, statusCode, err := m.Provider.AuthenticateLocal(req.Username, req.Password, req.ClientIP)
	if err != nil {
		_ = peer.send(MsgAuthVerifyResult, "", env.ID, AuthVerifyResp{OK: false, StatusCode: statusCode, Error: err.Error()})
		return
	}
	_ = peer.send(MsgAuthVerifyResult, "", env.ID, AuthVerifyResp{
		OK:        true,
		UserID:    userID,
		Username:  username,
		AuthEpoch: epoch,
	})
}

func (m *Manager) handleInboundAuthReauth(peer *peerConn, env Envelope) {
	var req AuthReauthReq
	if json.Unmarshal(env.Payload, &req) != nil {
		_ = peer.send(MsgAuthReauthResult, "", env.ID, AuthReauthResp{OK: false, StatusCode: http.StatusBadRequest, Error: "requisição inválida"})
		return
	}
	if m.Provider == nil {
		_ = peer.send(MsgAuthReauthResult, "", env.ID, AuthReauthResp{OK: false, StatusCode: http.StatusServiceUnavailable, Error: "autenticação indisponível"})
		return
	}
	userID, _, epoch, statusCode, err := m.Provider.AuthenticateLocal(req.Username, req.Password, req.ClientIP)
	if err != nil || userID != req.UserID {
		code := statusCode
		if code == 0 || code == http.StatusOK {
			code = http.StatusBadRequest
		}
		msg := "usuário ou senha inválidos"
		if err != nil && statusCode == http.StatusTooManyRequests {
			msg = err.Error()
		}
		_ = peer.send(MsgAuthReauthResult, "", env.ID, AuthReauthResp{OK: false, StatusCode: code, Error: msg})
		return
	}
	_ = peer.send(MsgAuthReauthResult, "", env.ID, AuthReauthResp{OK: true, AuthEpoch: epoch})
}

func (m *Manager) handleInboundAuthStatus(peer *peerConn, env Envelope) {
	var req AuthStatusReq
	if json.Unmarshal(env.Payload, &req) != nil || m.Provider == nil {
		_ = peer.send(MsgAuthStatusResult, "", env.ID, AuthStatusResp{Exists: false})
		return
	}
	for _, u := range m.Provider.LocalAdminUsers() {
		if u.UserID == req.UserID {
			_ = peer.send(MsgAuthStatusResult, "", env.ID, AuthStatusResp{
				Exists:    true,
				Username:  u.Username,
				AuthEpoch: u.AuthEpoch,
			})
			return
		}
	}
	_ = peer.send(MsgAuthStatusResult, "", env.ID, AuthStatusResp{Exists: false})
}

func (m *Manager) requiredStepUpForCommand(cmd ExecCommandReq) string {
	switch cmd.Kind {
	case CmdDatabaseCredentials:
		return StepUpDatabasePassword
	case CmdDatabaseCertificate:
		var p struct {
			Format string `json:"format"`
		}
		if json.Unmarshal(cmd.Payload, &p) == nil && p.Format == "key" {
			return StepUpDatabaseExportKey
		}
	case CmdDatabaseChange:
		var p databases.Change
		if json.Unmarshal(cmd.Payload, &p) == nil && p.Action == "delete" {
			return StepUpDatabaseDelete
		}
	}
	return ""
}

func (m *Manager) verifyInboundStepUp(primaryPub *ecdsa.PublicKey, cmd ExecCommandReq, requiredAction string) error {
	if requiredAction == "" {
		return nil
	}
	if cmd.StepUp == nil {
		return errors.New("esta ação sensível exige autorização revalidada")
	}
	g := *cmd.StepUp
	if err := VerifyStepUpGrant(primaryPub, g); err != nil {
		return err
	}
	if g.TargetNodeID != m.InstallationID {
		return errors.New("autorização sensível não pertence a este computador")
	}
	if g.ResourceID != cmd.ResourceID || g.Action != requiredAction {
		return errors.New("autorização sensível não corresponde à instância ou ação")
	}
	if g.IssuerNodeID != cmd.Actor.IssuerNodeID || g.UserID != cmd.Actor.UserID {
		return errors.New("autorização sensível não corresponde ao usuário autenticado")
	}
	now := time.Now()
	m.stepUpMu.Lock()
	defer m.stepUpMu.Unlock()
	for id, exp := range m.usedStepUpGrants {
		if now.After(exp) {
			delete(m.usedStepUpGrants, id)
		}
	}
	if _, replayed := m.usedStepUpGrants[g.GrantID]; replayed {
		return errors.New("autorização sensível já foi utilizada")
	}
	m.usedStepUpGrants[g.GrantID] = time.Unix(g.ExpiresAt, 0).Add(time.Minute)
	return nil
}

func (m *Manager) handleInboundExecCommand(ctx context.Context, peer *peerConn, primaryPub *ecdsa.PublicKey, env Envelope) {
	var cmd ExecCommandReq
	if json.Unmarshal(env.Payload, &cmd) != nil {
		_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusBadRequest, Error: "comando inválido"})
		return
	}
	st := m.State()
	// Host-side authorization check: verify active link, explicit allowed command kind, and local delegation!
	if st.LinkStatus != LinkStatusLinked && st.LinkStatus != LinkStatusSyncing {
		_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusForbidden, Error: "este computador não está vinculado ao painel principal"})
		return
	}
	if !OperationDelegated(st.DelegatedOps, cmd.Kind) {
		_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusForbidden, Error: "operação não delegada por este computador"})
		return
	}
	if reqAction := m.requiredStepUpForCommand(cmd); reqAction != "" {
		if err := m.verifyInboundStepUp(primaryPub, cmd, reqAction); err != nil {
			m.RecordAudit(AuditEntry{
				ActorNodeID:   cmd.Actor.IssuerNodeID,
				ActorUserID:   cmd.Actor.UserID,
				ActorUsername: cmd.Actor.Username,
				TargetNodeID:  m.InstallationID,
				ResourceType:  commandResourceType(cmd.Kind),
				ResourceID:    cmd.ResourceID,
				Operation:     cmd.Kind,
				OperationID:   cmd.OperationID,
				Result:        "denied_stepup",
				Detail:        err.Error(),
			})
			_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusForbidden, Error: err.Error()})
			return
		}
	}

	isMutating := cmd.Kind == CmdProjectAction || cmd.Kind == CmdDatabaseCreate || cmd.Kind == CmdDatabaseChange || cmd.Kind == CmdDatabaseReveal
	if isMutating && cmd.OperationID != "" {
		existing, inserted, err := m.tryBeginRemoteOp(RemoteOpRecord{
			OperationID:  cmd.OperationID,
			Direction:    "inbound",
			TargetNodeID: m.InstallationID,
			ResourceType: commandResourceType(cmd.Kind),
			ResourceID:   cmd.ResourceID,
			Action:       cmd.Kind,
			Status:       "in_progress",
		})
		if err != nil {
			_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusInternalServerError, Error: err.Error()})
			return
		}
		if !inserted {
			switch existing.Status {
			case "completed":
				_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: true, StatusCode: http.StatusOK, Data: json.RawMessage(existing.ResultJSON)})
			case "failed":
				_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusConflict, Error: existing.ErrorText})
			default:
				_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusConflict, Error: "operação duplicada já em andamento"})
			}
			return
		}
	}

	if m.Provider == nil {
		if isMutating && cmd.OperationID != "" {
			m.finishRemoteOp(cmd.OperationID, "failed", "", "executor local indisponível")
		}
		_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: http.StatusServiceUnavailable, Error: "executor local indisponível"})
		return
	}

	data, statusCode, err := m.Provider.ExecuteLocalCommand(ctx, cmd)
	if err != nil {
		if statusCode == 0 {
			statusCode = http.StatusBadRequest
		}
		if isMutating && cmd.OperationID != "" {
			m.finishRemoteOp(cmd.OperationID, "failed", "", err.Error())
		}
		m.RecordAudit(AuditEntry{
			ActorNodeID:   cmd.Actor.IssuerNodeID,
			ActorUserID:   cmd.Actor.UserID,
			ActorUsername: cmd.Actor.Username,
			TargetNodeID:  m.InstallationID,
			ResourceType:  commandResourceType(cmd.Kind),
			ResourceID:    cmd.ResourceID,
			Operation:     cmd.Kind,
			OperationID:   cmd.OperationID,
			Result:        "error",
			Detail:        err.Error(),
		})
		_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: false, StatusCode: statusCode, Error: err.Error()})
		return
	}
	if statusCode == 0 {
		statusCode = http.StatusOK
	}
	if isMutating && cmd.OperationID != "" {
		m.finishRemoteOp(cmd.OperationID, "completed", string(data), "")
	}
	m.RecordAudit(AuditEntry{
		ActorNodeID:   cmd.Actor.IssuerNodeID,
		ActorUserID:   cmd.Actor.UserID,
		ActorUsername: cmd.Actor.Username,
		TargetNodeID:  m.InstallationID,
		ResourceType:  commandResourceType(cmd.Kind),
		ResourceID:    cmd.ResourceID,
		Operation:     cmd.Kind,
		OperationID:   cmd.OperationID,
		Result:        "success",
	})
	_ = peer.send(MsgExecResult, "", env.ID, ExecCommandResp{OK: true, StatusCode: statusCode, Data: data})
	if isMutating {
		m.TriggerInventorySync()
	}
}
